export const DICTS: Record<Lang, Dict> = { en, hi };

/** Persisted language preference, synced across components in the same tab. */
export function useLang(): [Lang, (l: Lang) => void, Dict] {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const read = () => setLangState(localStorage.getItem(KEY) === "hi" ? "hi" : "en");
    read();
    window.addEventListener(EVT, read);
    return () => window.removeEventListener(EVT, read);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem(KEY, l);
    window.dispatchEvent(new Event(EVT));
  }, []);
  return [lang, setLang, DICTS[lang]];
}

export function LangToggleLabel(lang: Lang) {
  return lang === "en" ? "हिंदी" : "English";
}
